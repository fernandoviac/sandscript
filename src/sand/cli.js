/**
 * Sand CLI
 *
 * Multi-modal CLI for SandScript. Docker-style subcommands.
 * REPL is default.
 */

import { VERSION } from '../version.js';
import { SessionManager } from './sessions.js';
import { formatError } from '../fuel/semantic-errors.js';
import { checkSyntax } from '../fuel/syntax-check.js';
import { findStructuralIssues } from '../fuel/structural-checks.js';
import { UncaughtScriptError } from '../runtime/errors.js';


// =============================================================================
// Shared session manager (persists across commands in same process)
// =============================================================================

let sessionManager = null;

async function getSessionManager() {
  if (!sessionManager) {
    sessionManager = new SessionManager();
    await sessionManager.init();
  }
  return sessionManager;
}

// =============================================================================
// Commands
// =============================================================================

async function scriptCommand(args, flags) {
  const code = args[0];
  if (!code) {
    console.error('Usage: sand script "code"');
    Deno.exit(1);
  }

  const sessions = await getSessionManager();
  await rotateIfStuckAndReport(sessions);
  const { session } = await sessions.current();

  let parseResult;
  try {
    parseResult = session.parse(code);
  } catch (parseError) {
    const retrySession = await rotateOnCodeBlockFullAndReport(sessions, parseError);
    if (!retrySession) {
      console.error(parseError.message);
      Deno.exit(1);
    }
    await runParsedScript(retrySession, retrySession.parse(code), sessions, flags);
    return;
  }
  await runParsedScript(session, parseResult, sessions, flags);
}

/**
 * Finish running a script once it has parsed successfully: set the
 * instruction pointer, run to completion, and apply --verbose/--save.
 * Factored out so the normal path and the rotate-and-retry path (see
 * rotateOnCodeBlockFullAndReport) share one run/report tail instead of
 * duplicating it.
 */
async function runParsedScript(session, parseResult, sessions, flags) {
  session.mem.setContextInstructionIndex(0, parseResult.startIndex);

  let result;
  try {
    result = session.run(0, 100000);
  } catch (err) {
    if (err instanceof UncaughtScriptError) {
      sessions.markDirty();
      console.error(err.message);
      Deno.exit(1);
    }
    throw err;
  }
  if (result.status === 'error') {
    console.error(formatError(result.error));
    Deno.exit(1);
  }

  sessions.markDirty();

  // Aspirational: a successful `sand script` prints nothing on this
  // path unless --verbose is passed — exit 0, empty stdout, whether
  // the script was `let x = 1` or something that silently no-ops. A
  // caller (especially a non-interactive one) has no positive
  // confirmation short of a follow-up `sand get`. The fix would mirror
  // a REPL's own convention: print the value of a trailing bare
  // expression statement (not a declaration, which has no value).
  // Needs the parser to track "was the last statement an expression,
  // and what did it evaluate to" — no such plumbing exists yet.

  if (flags.verbose) {
    printScope(session);
  }

  if (flags.save) {
    await sessions.saveCurrentSession();
  }
}

/**
 * If the current session is the anonymous auto-created scratch session
 * (never explicitly named via `session new`/`session use`/`session
 * save`) and it's stuck at `status: 'error'` from a prior run, retire it
 * for a fresh one and report the rotation to stderr. Named sessions are
 * never touched here — a stuck named session is left for the user to
 * deal with explicitly, same as before this existed.
 */
async function rotateIfStuckAndReport(sessions) {
  const result = await sessions.rotateIfStuck();
  if (result.rotated) {
    console.error(`note: previous session hit an error and was retired; now using '${result.name}'`);
  }
}

/**
 * Called only after session.parse() has thrown. If the failure is the
 * code block filling up AND the current session is the anonymous
 * auto-created scratch session, retire it for a fresh one, report the
 * rotation to stderr, and return the new session so the caller can
 * retry the same parse once. Returns null for every other case (wrong
 * error, or a named session) so the caller surfaces the original error
 * exactly as before this existed.
 */
async function rotateOnCodeBlockFullAndReport(sessions, parseError) {
  if (!parseError.message.includes('Out of memory: code block collided with heap')) {
    return null;
  }
  if (!sessions.isCurrentAutoGenerated()) {
    return null;
  }
  const rotated = await sessions.rotate();
  console.error(`note: session was full and was retired; now using '${rotated.name}'`);
  return (await sessions.current()).session;
}

async function getCommand(args, flags) {
  const sessions = await getSessionManager();
  const { session } = await sessions.current();

  if (args.length === 0) {
    // List all variables. Session name goes to stderr (matching the
    // rotation notices' stream) so stdout stays exactly the bare,
    // comma-joined variable list — a script parsing stdout shouldn't
    // have to skip a header line to get at the data.
    console.error(`session: ${sessions.getCurrentName()}`);
    const vars = session.listVars(0);
    if (vars.length === 0) {
      console.log('(no variables)');
    } else {
      console.log(vars.join(', '));
    }
  } else {
    // Get specific variable
    const name = args[0];
    const value = session.get(0, name);
    if (value === undefined) {
      console.error(`undefined: ${name}`);
      Deno.exit(1);
    }
    console.log(JSON.stringify(toJsonSafe(value)));
  }
}

async function stepCommand(args, flags) {
  const sessions = await getSessionManager();
  const { session } = await sessions.current();

  if (args.length > 0 && isNaN(parseInt(args[0]))) {
    // First arg is code to load
    const code = args[0];
    const slot = 0;
    let parseResult;
    try {
      parseResult = session.parse(code);
    } catch (parseError) {
      console.error(parseError.message);
      Deno.exit(1);
    }
    session.mem.setContextInstructionIndex(slot, parseResult.startIndex);

    // fuel=0 means load only - code is ready to run, report as loaded
    console.log('loaded');
    sessions.markDirty();
  } else {
    // Resume execution
    const slot = 0;
    const fuel = args.length > 0 ? parseInt(args[0]) : 10000;
    const result = session.run(slot, fuel);

    const status = result.status === 'error' ? 'runtime_error' : result.status;
    // session.run returns remaining fuel as `result.fuel`; consumed is the
    // budget minus what's left.
    console.log(JSON.stringify({ status, fuelUsed: fuel - result.fuel }));
    sessions.markDirty();
  }
}

async function inspectCommand(args, flags) {
  const sessions = await getSessionManager();
  const { session } = await sessions.current();

  const what = args[0] || 'state';
  const state = session.state(0);

  switch (what) {
    case 'state':
      console.log(`status: ${state.status}`);
      console.log(`instruction: ${state.instruction}/${state.instructionCount}`);
      console.log(`callStack: ${state.callStackDepth}`);
      console.log(`fuel: ${state.fuel}`);
      break;

    case 'scope':
      printScope(session);
      break;

    case 'stack':
      console.log(`pending: [${state.pending.map(v => JSON.stringify(v)).join(', ')}]`);
      console.log(`callStackDepth: ${state.callStackDepth}`);
      break;

    case 'memory': {
      const address = args[1] ? (parseInt(args[1], 16) || parseInt(args[1])) : 0;
      const length = args[2] ? parseInt(args[2]) : 64;
      const bytes = new Uint8Array(session.mem.memory.buffer, address, length);
      const hex = Array.from(bytes).map(b => b.toString(16).padStart(2, '0')).join(' ');
      console.log(`@${address} (${length} bytes):`);
      console.log(hex);
      break;
    }

    default:
      console.log(JSON.stringify(state));
  }
}

async function sessionCommand(args, flags) {
  const [subcommand, ...rest] = args;
  const sessions = await getSessionManager();

  switch (subcommand) {
    case 'list': {
      const list = await sessions.listSessions();
      if (list.length === 0) {
        console.log('(no sessions)');
      } else {
        for (const s of list) {
          const marker = s.current ? '* ' : '  ';
          console.log(`${marker}${s.name}`);
        }
      }
      break;
    }

    case 'use': {
      const name = rest[0];
      if (!name) {
        console.error('Usage: sand session use <name>');
        Deno.exit(1);
      }
      const result = await sessions.useSession(name);
      if (result.notFound) {
        console.error(`session not found: ${name}`);
        Deno.exit(1);
      }
      if (result.loadError) {
        console.error(`failed to load session ${name}: ${result.loadError}`);
        Deno.exit(1);
      }
      console.log(`switched to ${result.name}`);
      break;
    }

    case 'new': {
      const name = rest[0];
      const result = await sessions.newSession(name);
      console.log(`created ${result.name}`);
      break;
    }

    case 'save': {
      const result = await sessions.saveCurrentSession();
      console.log(`saved ${result.name}`);
      break;
    }

    case 'save-as': {
      const name = rest[0];
      if (!name) {
        console.error('Usage: sand session save-as <name>');
        Deno.exit(1);
      }
      const result = await sessions.saveCurrentSessionAs(name);
      console.log(`saved as ${result.name}`);
      break;
    }

    case 'rename': {
      const name = rest[0];
      if (!name) {
        console.error('Usage: sand session rename <name>');
        Deno.exit(1);
      }
      const result = await sessions.renameSession(name);
      console.log(`renamed to ${result.name}`);
      break;
    }

    case 'delete': {
      const name = rest[0];
      if (!name) {
        console.error('Usage: sand session delete <name>');
        Deno.exit(1);
      }
      const result = await sessions.deleteSession(name);
      if (result.deleted) {
        console.log(`deleted ${name}`);
      } else {
        console.log(`not found: ${name}`);
      }
      break;
    }

    case 'export': {
      const path = rest[0];
      if (!path) {
        console.error('Usage: sand session export <path>');
        Deno.exit(1);
      }
      const name = sessions.getCurrentName();
      const result = await sessions.exportSession(name, path);
      console.log(`exported to ${result.path}`);
      break;
    }

    default:
      console.error('Usage: sand session <list|use|new|save|save-as|rename|delete|export>');
      Deno.exit(1);
  }
}

// =============================================================================
// REPL
// =============================================================================

async function runRepl() {
  const sessions = await getSessionManager();

  console.log('sand REPL (Ctrl+D or /exit to quit, /help for commands)');

  while (true) {
    const line = prompt('sand>');
    if (line === null) {
      // EOF (Ctrl+D)
      await sessions.saveAll();
      break;
    }

    const trimmed = line.trim();
    if (trimmed === '') continue;

    try {
      if (trimmed.startsWith('/')) {
        // Command mode
        const cmdLine = trimmed.slice(1);

        // Handle REPL-specific commands
        if (cmdLine === 'exit' || cmdLine === 'quit' || cmdLine === 'q') {
          await sessions.saveAll();
          break;
        }

        if (cmdLine === 'help' || cmdLine === 'h' || cmdLine === '?') {
          printReplHelp();
          continue;
        }

        const args = parseCommandLine(cmdLine);
        await runCommand(args);
      } else {
        // Implicit script
        await runCommand(['script', trimmed]);
      }
    } catch (err) {
      console.error(err.message);
    }
  }
}

function printReplHelp() {
  console.log(`
REPL Commands (prefix with /):
  /get [name]           Get variable value (or list all)
  /inspect [what]       Inspect state/scope/stack/memory
  /step ["code"]        Load code without running
  /step [fuel]          Resume with fuel limit
  /session list         List sessions
  /session use <name>   Switch session
  /session new [name]   New session
  /session save         Save current session
  /session save-as <n>  Fork to new name
  /exit, /quit, /q      Exit REPL
  /help, /h, /?         This help

Code runs directly (no / prefix):
  let x = 10
  let y = x * 2
`);
}

async function checkCommand(args, flags) {
  const path = args[0];
  if (!path) {
    console.error('Usage: sand check <file>');
    Deno.exit(1);
  }

  let code;
  try {
    code = await Deno.readTextFile(path);
  } catch (err) {
    console.error(`cannot read ${path}: ${err.message}`);
    Deno.exit(1);
  }

  if (code.startsWith('#!')) {
    const newlineIndex = code.indexOf('\n');
    if (newlineIndex !== -1) {
      code = code.slice(newlineIndex + 1);
    }
  }

  const result = checkSyntax(code);
  if (!result.ok) {
    console.error(formatError(result));
    Deno.exit(1);
  }

  const { findings } = findStructuralIssues(code);
  if (findings.length > 0) {
    for (const finding of findings) {
      console.error(`${finding.rule}: ${finding.message} (line ${finding.line}, col ${finding.column})`);
    }
    Deno.exit(1);
  }
}

// =============================================================================
// File runner
// =============================================================================

async function runFile(path, flags) {
  let code = await Deno.readTextFile(path);

  // Strip shebang if present
  if (code.startsWith('#!')) {
    const newlineIndex = code.indexOf('\n');
    if (newlineIndex !== -1) {
      code = code.slice(newlineIndex + 1);
    }
  }

  const sessions = await getSessionManager();
  await rotateIfStuckAndReport(sessions);
  const { session } = await sessions.current();

  let parseResult;
  try {
    parseResult = session.parse(code);
  } catch (parseError) {
    const retrySession = await rotateOnCodeBlockFullAndReport(sessions, parseError);
    if (!retrySession) {
      console.error(parseError.message);
      Deno.exit(1);
    }
    await runParsedScript(retrySession, retrySession.parse(code), sessions, flags);
    return;
  }
  await runParsedScript(session, parseResult, sessions, flags);
}


/**
 * Convert a session.get() readback value into something JSON.stringify
 * can serialize losslessly. Unlike formatValue (the human-facing
 * pretty-printer used by --verbose/printScope), this never truncates
 * and never abbreviates — a script consuming `sand get`'s output wants
 * the real data, not a preview.
 *
 * BigInt has no native JSON representation, so it's tagged as
 * {"$bigint": "<decimal digits>"} (a string, since JSON numbers can't
 * hold arbitrary precision) rather than silently coerced to a Number
 * (lossy) or a bare string (indistinguishable from an actual string
 * value). Every SandScript readback shape bottoms out in plain
 * primitives, arrays, and plain {kind: '...'} objects (rational,
 * complex, algebraic, theorem, expression, matrix — see
 * memory-reader.js's unmarshal* functions) with BigInts nested
 * throughout, so recursing through plain arrays/objects reaches them
 * all uniformly — no shape needs special-casing beyond BigInt itself.
 *
 * Throws on anything outside that value space (function, symbol) —
 * session.get() is never expected to return one, so seeing one here
 * means something upstream changed in a way worth knowing loudly,
 * not silently dropping the key.
 */
export function toJsonSafe(value) {
  if (value === null || value === undefined) return null;
  if (typeof value === 'bigint') return { $bigint: value.toString() };
  if (typeof value === 'number' || typeof value === 'string' || typeof value === 'boolean') {
    return value;
  }
  if (Array.isArray(value)) {
    return value.map(toJsonSafe);
  }
  if (typeof value === 'object') {
    const out = {};
    for (const key of Object.keys(value)) {
      out[key] = toJsonSafe(value[key]);
    }
    return out;
  }
  throw new TypeError(`toJsonSafe: unsupported value type ${typeof value}`);
}

export function formatValue(value, depth = 0, seen = new WeakSet()) {
  const MAX_DEPTH = 3;
  const MAX_STRING_LEN = 200;
  const MAX_NESTED_STRING_LEN = 50;
  const MAX_ITEMS = 20;

  if (value === null) return 'null';
  if (value === undefined) return 'undefined';

  if (typeof value === 'string') {
    const maxLen = depth === 0 ? MAX_STRING_LEN : MAX_NESTED_STRING_LEN;
    const truncated = value.length > maxLen ? value.slice(0, maxLen) + '...' : value;
    return depth === 0 ? truncated : `"${truncated}"`;
  }

  if (typeof value === 'number' || typeof value === 'boolean') {
    return String(value);
  }

  if (typeof value === 'function') {
    return value.name ? `[Function: ${value.name}]` : '[Function]';
  }

  if (typeof value === 'object') {
    if (seen.has(value)) return '[Circular]';
    seen.add(value);

    if (depth >= MAX_DEPTH) {
      return Array.isArray(value) ? '[...]' : '{...}';
    }

    if (Array.isArray(value)) {
      if (value.length === 0) return '[]';
      const items = value.slice(0, MAX_ITEMS).map(v => formatValue(v, depth + 1, seen));
      const more = value.length > MAX_ITEMS ? `, ... ${value.length - MAX_ITEMS} more` : '';
      return `[${items.join(', ')}${more}]`;
    }

    const keys = Object.keys(value);
    if (keys.length === 0) return '{  }';
    const items = keys.slice(0, MAX_ITEMS).map(k => `${k}: ${formatValue(value[k], depth + 1, seen)}`);
    const more = keys.length > MAX_ITEMS ? `, ... ${keys.length - MAX_ITEMS} more` : '';
    return `{ ${items.join(', ')}${more} }`;
  }

  return String(value);
}

function printScope(session) {
  const vars = session.listVars(0);
  for (const name of vars) {
    const value = session.get(0, name);
    console.log(`${name} = ${formatValue(value)}`);
  }
}

function parseCommandLine(line) {
  // Simple arg parser: split on spaces, respecting quotes
  const args = [];
  let current = '';
  let inQuote = false;
  let quoteChar = '';

  for (const char of line) {
    if (inQuote) {
      if (char === quoteChar) {
        inQuote = false;
      } else {
        current += char;
      }
    } else {
      if (char === '"' || char === "'") {
        inQuote = true;
        quoteChar = char;
      } else if (char === ' ') {
        if (current) {
          args.push(current);
          current = '';
        }
      } else {
        current += char;
      }
    }
  }

  if (current) {
    args.push(current);
  }

  return args;
}

function parseFlags(args) {
  const flags = {};
  const positional = [];

  for (const arg of args) {
    if (arg === '--verbose' || arg === '-v') {
      flags.verbose = true;
    } else if (arg === '--save') {
      flags.save = true;
    } else if (arg.startsWith('--')) {
      // Unknown flag, ignore for now
    } else if (arg.startsWith('-')) {
      // Unknown short flag, ignore for now
    } else {
      positional.push(arg);
    }
  }

  return { flags, positional };
}

// =============================================================================
// Command dispatch
// =============================================================================

async function runCommand(args) {
  const [command, ...rest] = args;
  const { flags, positional } = parseFlags(rest);

  switch (command) {
    case 'script':
      await scriptCommand(positional, flags);
      break;

    case 'check':
      await checkCommand(positional, flags);
      break;

    case 'get':
      await getCommand(positional, flags);
      break;

    case 'step':
      await stepCommand(positional, flags);
      break;

    case 'inspect':
      await inspectCommand(positional, flags);
      break;

    case 'session':
      await sessionCommand(positional, flags);
      break;

    default:
      // Check if it's a file
      if (command && (command.endsWith('.ss') || command.endsWith('.sand') || await fileExists(command))) {
        await runFile(command, flags);
      } else {
        console.error(`Unknown command: ${command}`);
        console.error('Run "sand --help" for usage');
        Deno.exit(1);
      }
  }
}

async function fileExists(path) {
  try {
    await Deno.stat(path);
    return true;
  } catch {
    return false;
  }
}


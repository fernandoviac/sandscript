const FUEL_DIRECTORY = new URL('../src/fuel/', import.meta.url).pathname;
const WAT_PATH = `${FUEL_DIRECTORY}regex-engine.wat`;
const WASM_PATH = `${FUEL_DIRECTORY}regex-engine.wasm`;
const JAVASCRIPT_PATH = `${FUEL_DIRECTORY}regex-engine.wasm.js`;

export async function buildRegexWasm() {
  const command = new Deno.Command('wat2wasm', {
    args: ['--enable-threads', WAT_PATH, '-o', WASM_PATH],
    stdout: 'piped',
    stderr: 'piped',
  });
  const { code, stderr } = await command.output();
  if (code !== 0) {
    throw new Error(`wat2wasm failed for regex-engine.wat:\n${new TextDecoder().decode(stderr)}`);
  }

  const wasmBinary = await Deno.readFile(WASM_PATH);
  let binaryString = '';
  for (const byte of wasmBinary) binaryString += String.fromCharCode(byte);
  const base64 = btoa(binaryString);
  const javascript = `// Generated by tools/build-regex-wasm.js. Do not edit.\n\nexport const WASM_BASE64 = "${base64}";\n\nfunction decodeBase64(value) {\n  const binary = atob(value);\n  const bytes = new Uint8Array(binary.length);\n  for (let index = 0; index < binary.length; index++) bytes[index] = binary.charCodeAt(index);\n  return bytes;\n}\n\nexport function compileRegexModule() {\n  return new WebAssembly.Module(decodeBase64(WASM_BASE64));\n}\n\nexport function instantiateRegexSync(memory, module = compileRegexModule()) {\n  return new WebAssembly.Instance(module, { env: { memory } });\n}\n\nexport async function instantiateRegex(memory) {\n  const module = await WebAssembly.compile(decodeBase64(WASM_BASE64));\n  return WebAssembly.instantiate(module, { env: { memory } });\n}\n`;
  await Deno.writeTextFile(JAVASCRIPT_PATH, javascript);
}

if (import.meta.main) {
  await buildRegexWasm();
}

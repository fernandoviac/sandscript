const FUEL_DIRECTORY = new URL('../src/fuel/', import.meta.url).pathname;
const WAT_PATH = `${FUEL_DIRECTORY}schema-engine.wat`;
const WASM_PATH = `${FUEL_DIRECTORY}schema-engine.wasm`;
const JAVASCRIPT_PATH = `${FUEL_DIRECTORY}schema-engine.wasm.js`;

export async function buildSchemaWasm() {
  const command = new Deno.Command('wat2wasm', {
    args: ['--enable-threads', WAT_PATH, '-o', WASM_PATH],
    stdout: 'piped',
    stderr: 'piped',
  });
  const { code, stderr } = await command.output();
  if (code !== 0) {
    throw new Error(`wat2wasm failed for schema-engine.wat:\n${new TextDecoder().decode(stderr)}`);
  }

  const wasmBinary = await Deno.readFile(WASM_PATH);
  let binaryString = '';
  for (const byte of wasmBinary) binaryString += String.fromCharCode(byte);
  const base64 = btoa(binaryString);
  const javascript = `// Generated by tools/build-schema-wasm.js. Do not edit.
//
// The schema engine imports the regex engine's exports under the "regex"
// namespace; both must be instantiated against the same memory, regex
// first. instantiateSchemaSync takes the regex instance (or its exports).

export const WASM_BASE64 = "${base64}";

function decodeBase64(value) {
  const binary = atob(value);
  const bytes = new Uint8Array(binary.length);
  for (let index = 0; index < binary.length; index++) bytes[index] = binary.charCodeAt(index);
  return bytes;
}

export function compileSchemaModule() {
  return new WebAssembly.Module(decodeBase64(WASM_BASE64));
}

function regexImports(regex) {
  return regex.exports ? regex.exports : regex;
}

export function instantiateSchemaSync(memory, regex, module = compileSchemaModule()) {
  return new WebAssembly.Instance(module, { env: { memory }, regex: regexImports(regex) });
}

export async function instantiateSchema(memory, regex) {
  const module = await WebAssembly.compile(decodeBase64(WASM_BASE64));
  return WebAssembly.instantiate(module, { env: { memory }, regex: regexImports(regex) });
}
`;
  await Deno.writeTextFile(JAVASCRIPT_PATH, javascript);
}

if (import.meta.main) {
  await buildSchemaWasm();
}
